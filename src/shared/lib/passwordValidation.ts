import * as Yup from 'yup'

export const passwordSchema = Yup.string()
  .min(8, 'Пароль должен содержать минимум 8 символов')
  .matches(/[a-z]/, 'Добавьте строчную латинскую букву')
  .matches(/[A-Z]/, 'Добавьте заглавную латинскую букву')
  .matches(/[0-9]/, 'Добавьте цифру')
  // Знаки пунктуации и символы, например !, ?, @, #
  .matches(/[\p{P}\p{S}]/u, 'Добавьте спецсимвол')
